/**
 * Export every jar opened and every tip sent, read from the contract's events.
 *
 *   npm run users:export
 *
 * RPC keeps events for about a week, so this file is append-only: each run
 * reads from the last ledger it saw and adds new rows to
 * `docs/proof/<network>-events.csv`. Run it at least weekly (CI does) and the
 * file stays a complete record. Every row carries its transaction hash, so any
 * line can be checked on an explorer.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { config as load } from "dotenv";

load({ path: ".env.local" });
load();

const { rpc, scValToNative } = await import("@stellar/stellar-sdk");
const { CONFIG, tokenByContract } = await import("../src/lib/config.ts");

if (!CONFIG.contractId) throw new Error("PUBLIC_TIPJAR_CONTRACT_ID is not set");

const dir = "docs/proof";
const csvPath = `${dir}/${CONFIG.network}-events.csv`;
const summaryPath = `${dir}/${CONFIG.network}-summary.md`;
const HEADER = "kind,address,handle,amount,token,message,ledger,closed_at,tx_hash,event_id";

mkdirSync(dir, { recursive: true });
const existing = existsSync(csvPath) ? readFileSync(csvPath, "utf8").trim().split("\n").slice(1) : [];
const seen = new Set(existing.map((l) => l.split(",").at(-1)));
const lastLedger = existing.reduce((m, l) => Math.max(m, Number(parseCsv(l)[6]) || 0), 0);

const server = new rpc.Server(CONFIG.rpcUrl);
const latest = await server.getLatestLedger();
// RPC refuses a start ledger older than its retention window.
const oldest = Math.max(1, latest.sequence - 120_000);
const startLedger = Math.max(lastLedger, oldest);
if (lastLedger && lastLedger < oldest) {
  console.warn(`! gap: last export ended at ${lastLedger}, RPC now starts at ${oldest}. Rows in between are lost to this script; check stellar.expert.`);
}

const rows: string[] = [];
const filters = [{ type: "contract" as const, contractIds: [CONFIG.contractId] }];
const WINDOW = 5_000;

// RPC scans a bounded range per request and can come back empty for a window
// that has no events, so walk the ledger range in windows and page within each.
for (let from = startLedger; from <= latest.sequence; from += WINDOW) {
  const to = Math.min(from + WINDOW, latest.sequence + 1);
  let cursor: string | undefined;
  for (;;) {
    const page = cursor
      ? await server.getEvents({ cursor, filters, limit: 200 })
      : await server.getEvents({ startLedger: from, endLedger: to, filters, limit: 200 });
    for (const ev of page.events) {
      if (ev.ledger >= to) continue;
      if (!seen.has(ev.id)) rows.push(...toRows(ev));
      seen.add(ev.id);
    }
    if (page.events.length < 200) break;
    cursor = page.cursor;
  }
}

type Ev = Awaited<ReturnType<typeof server.getEvents>>["events"][number];

function toRows(ev: Ev): string[] {
  const topics = ev.topic.map((t) => scValToNative(t));
  const data = scValToNative(ev.value) as Record<string, unknown>;
  const kind = String(topics[0]);
  if (kind === "registered") {
    return [csv(["register", String(data.owner), String(topics[1]), "", "", "", ev.ledger, ev.ledgerClosedAt, ev.txHash, ev.id])];
  }
  if (kind === "tipped") {
    const token = String(data.token);
    const t = tokenByContract(token);
    const amount = Number(BigInt(data.amount as bigint)) / 10 ** (t?.decimals ?? 7);
    return [
      csv([
        "tip",
        String(topics[2]),
        String(topics[1]),
        amount,
        t?.symbol ?? token,
        String(data.message ?? "").replace(/\s+/g, " "),
        ev.ledger,
        ev.ledgerClosedAt,
        ev.txHash,
        ev.id,
      ]),
    ];
  }
  return [];
}

const all = [...existing, ...rows];
writeFileSync(csvPath, [HEADER, ...all].join("\n") + "\n");

const parsed = all.map(parseCsv);
const wallets = new Set(parsed.map((r) => r[1]));
const creators = new Set(parsed.filter((r) => r[0] === "register").map((r) => r[1]));
const tippers = new Set(parsed.filter((r) => r[0] === "tip").map((r) => r[1]));
const tips = parsed.filter((r) => r[0] === "tip");
const byToken = new Map<string, number>();
for (const r of tips) byToken.set(r[4], (byToken.get(r[4]) ?? 0) + Number(r[3]));

const summary = `# On-chain activity · ${CONFIG.network}

Generated by \`npm run users:export\` from contract events. Every row in
[\`${CONFIG.network}-events.csv\`](./${CONFIG.network}-events.csv) links to a transaction.

| | |
|---|---|
| Contract | [\`${CONFIG.contractId}\`](${CONFIG.explorer}/contract/${CONFIG.contractId}) |
| Unique wallets | **${wallets.size}** |
| Jars opened | ${creators.size} |
| Wallets that tipped | ${tippers.size} |
| Tips | ${tips.length} |
${[...byToken].map(([k, v]) => `| Volume ${k} | ${v.toLocaleString("en-US", { maximumFractionDigits: 7 })} |\n`).join("")}| Last ledger read | ${latest.sequence} |
`;
writeFileSync(summaryPath, summary);

console.log(`${rows.length} new rows · ${wallets.size} unique wallets · ${tips.length} tips → ${csvPath}`);

function csv(cells: (string | number)[]): string {
  return cells
    .map((c) => {
      const s = String(c);
      return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
    })
    .join(",");
}

function parseCsv(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") {
      out.push(cur);
      cur = "";
    } else cur += ch;
  }
  out.push(cur);
  return out;
}
